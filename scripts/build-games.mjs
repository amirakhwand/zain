// ============================================================================
// DOMINO: place every domino so each region's rule is met. Each puzzle is
// built from a real solution, and a solver proves the answer is unique.
// ============================================================================
{
  const LEVELS = { easy: { k: 5, blank: 0.1 }, medium: { k: 7, blank: 0.15 }, hard: { k: 8, blank: 0.08 } };
  const key = (r, c) => r * 8 + c;
  function makeBoard(k, r) {
    const cells = new Set(), dominoes = [];
    const tryAdd = (a, b) => { if (cells.has(a) || cells.has(b)) return false; cells.add(a); cells.add(b); dominoes.push([a, b]); return true; };
    tryAdd(key(3, 3), key(3, 4));
    let guard = 0;
    while (dominoes.length < k && guard++ < 5000) {
      const list = [...cells]; const base = list[Math.floor(r() * list.length)];
      const br = Math.floor(base / 8), bc = base % 8;
      const dirs = [[0, 1], [1, 0], [0, -1], [-1, 0]];
      const [dr, dc] = dirs[Math.floor(r() * 4)];
      const ar = br + dr, ac = bc + dc;
      const [er, ec] = dirs[Math.floor(r() * 4)];
      const br2 = ar + er, bc2 = ac + ec;
      if ([ar, br2].some((x) => x < 0 || x > 6) || [ac, bc2].some((x) => x < 0 || x > 7)) continue;
      if (key(br2, bc2) === base) continue;
      tryAdd(key(ar, ac), key(br2, bc2));
    }
    return { cells: [...cells].sort((a, b) => a - b), dominoes };
  }
  function makeRegions(cells, val, blankP, r) {
    const left = new Set(cells), regions = [];
    const adj = (a) => [a - 8, a + 8, a % 8 ? a - 1 : -1, a % 8 < 7 ? a + 1 : -1].filter((x) => left.has(x));
    while (left.size) {
      const start = [...left][Math.floor(r() * left.size)];
      const size = 1 + Math.floor(r() * 4), reg = [start]; left.delete(start);
      while (reg.length < size) {
        const opts = reg.flatMap(adj); if (!opts.length) break;
        const pick = opts[Math.floor(r() * opts.length)]; reg.push(pick); left.delete(pick);
      }
      const vs = reg.map((c) => val[c]), sum = vs.reduce((a, b) => a + b, 0);
      let rule;
      const roll = r();
      if (roll < blankP) rule = { t: "none" };
      else if (reg.length > 1 && vs.every((v) => v === vs[0]) && roll < 0.7) rule = { t: "eq" };
      else if (reg.length > 2 && new Set(vs).size === vs.length && roll < 0.35) rule = { t: "ne" };
      else if (roll < 0.78) rule = { t: "sum", v: sum };
      else if (roll < 0.89 && sum < reg.length * 6) rule = { t: "lt", v: sum + 1 };
      else if (sum > 0) rule = { t: "gt", v: sum - 1 };
      else rule = { t: "sum", v: sum };
      regions.push({ cells: reg.sort((a, b) => a - b), ...rule });
    }
    return regions;
  }
  function check(region, vals, complete) {
    const vs = region.cells.map((c) => vals[c]).filter((v) => v !== undefined);
    const full = vs.length === region.cells.length, sum = vs.reduce((a, b) => a + b, 0), missing = region.cells.length - vs.length;
    switch (region.t) {
      case "sum": return full ? sum === region.v : sum <= region.v && sum + missing * 6 >= region.v;
      case "lt": return sum < region.v;
      case "gt": return full ? sum > region.v : sum + missing * 6 > region.v;
      case "eq": return vs.every((v) => v === vs[0]);
      case "ne": return new Set(vs).size === vs.length;
      default: return true;
    }
  }
  function countSolutions(cells, tray, regions, limit = 2) {
    const cellSet = new Set(cells), vals = {}, used = new Array(tray.length).fill(false);
    const regionOf = {}; regions.forEach((g) => g.cells.forEach((c) => (regionOf[c] = g)));
    const seen = new Set(); let count = 0;
    (function go() {
      if (count >= limit) return;
      const cell = cells.find((c) => vals[c] === undefined);
      if (cell === undefined) { const sig = cells.map((c) => vals[c]).join(""); if (!seen.has(sig)) { seen.add(sig); count++; } return; }
      for (const nbr of [cell + 1, cell + 8]) {
        if (!cellSet.has(nbr) || vals[nbr] !== undefined || (nbr === cell + 1 && cell % 8 === 7)) continue;
        const tried = new Set();
        for (let i = 0; i < tray.length; i++) {
          if (used[i]) continue;
          for (const [a, b] of [[tray[i][0], tray[i][1]], [tray[i][1], tray[i][0]]]) {
            const sig = a + "," + b; if (tried.has(sig)) continue; tried.add(sig);
            vals[cell] = a; vals[nbr] = b; used[i] = true;
            if (check(regionOf[cell], vals) && check(regionOf[nbr], vals)) go();
            delete vals[cell]; delete vals[nbr]; used[i] = false;
            if (count >= limit) return;
          }
        }
      }
    })();
    return count;
  }
  function makePuzzle(level, r) {
    const { k, blank } = LEVELS[level];
    const stats = { small: 0, loose: 0, multi: 0 };
    for (let attempt = 0; attempt < 2000; attempt++) {
      const { cells, dominoes } = makeBoard(k, r);
      if (dominoes.length < k) { stats.small++; continue; }
      const val = {};
      const tray = dominoes.map(([a, b]) => { val[a] = Math.floor(r() * 7); val[b] = Math.floor(r() * 7); return [val[a], val[b]]; });
      const regions = makeRegions(cells, val, blank, r);
      if (regions.filter((g) => g.t !== "none").length < regions.length * 0.6) { stats.loose++; continue; }
      // Tighten loose rules into exact sums until the answer is unique.
      let n = countSolutions(cells, tray, regions);
      for (let t = 0; n > 1 && t < regions.length; t++) {
        const loose = regions.filter((g) => ["none", "lt", "gt"].includes(g.t));
        if (!loose.length) break;
        const g = loose[Math.floor(r() * loose.length)];
        g.t = "sum"; g.v = g.cells.reduce((a, c) => a + val[c], 0);
        n = countSolutions(cells, tray, regions);
      }
      // Still ambiguous: split a cell off a multi-cell region as its own exact
      // sum. Each split pins one value, so this always ends with one answer.
      for (let t = 0; n > 1 && t < 12; t++) {
        const multi = regions.filter((g) => g.cells.length > 1);
        if (!multi.length) break;
        const g = multi[Math.floor(r() * multi.length)];
        const cell = g.cells.splice(Math.floor(r() * g.cells.length), 1)[0];
        if (g.t === "eq" || g.t === "ne") { /* still true for the remaining cells */ }
        else { g.t = "sum"; g.v = g.cells.reduce((a, c) => a + val[c], 0); }
        regions.push({ cells: [cell], t: "sum", v: val[cell] });
        n = countSolutions(cells, tray, regions);
      }
      if (n !== 1) { stats.multi++; continue; }
      // Keep it a puzzle: mostly multi-cell regions.
      if (regions.filter((g) => g.cells.length === 1).length > cells.length * 0.5) { stats.loose++; continue; }
      return { cells, tray: shuffle(tray, r).map((d) => (r() < 0.5 ? d : [d[1], d[0]])), regions, solution: dominoes.map(([a, b]) => [a, b, val[a], val[b]]) };
    }
    throw new Error("Domino: could not make a unique " + level + " puzzle " + JSON.stringify(stats));
  }
  const r = rng(81121), days = [];
  for (let d = 0; d < 365; d++) days.push({ easy: makePuzzle("easy", r), medium: makePuzzle("medium", r), hard: makePuzzle("hard", r) });
  write("domino", { launch: LAUNCH, days });
  console.log(`Domino: ${days.length} days x 3 levels, every puzzle has exactly one answer`);
}
