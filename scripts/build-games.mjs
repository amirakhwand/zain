// ============================================================================
// HUNCH: guess the 5-letter word in 6 tries
// ============================================================================
{
  const isPluralOrPast = (w) => (w.endsWith("s") && !/(ss|us|is|ous)$/.test(w)) || /[^e]ed$/.test(w) || w.endsWith("ied");
  const answers = words((w, t) => w.length === 5 && t <= 20 && !isPluralOrPast(w));
  const valid = words((w, t) => w.length === 5 && t <= 70);
  const r = rng(51121);
  const days = shuffle(answers, r).slice(0, DAYS);
  write("hunch", { launch: LAUNCH, days, valid: valid.filter((w) => !days.includes(w)).join(" ") });
  console.log(`Hunch: ${answers.length} possible answers, ${valid.length} valid guesses, scheduled ${days.length} days`);
}

// ============================================================================
// COMB: make words from 7 letters; every word uses the centre letter
// ============================================================================
{
  const pool = words((w, t) => w.length >= 4 && t <= 35 && !w.includes("s"));
  const pangrams = words((w, t) => t <= 35 && !w.includes("s") && new Set(w).size === 7);
  const masks = new Map(); // 7-letter set -> pangram words
  for (const w of pangrams) { const k = [...new Set(w)].sort().join(""); if (!masks.has(k)) masks.set(k, []); masks.get(k).push(w); }
  const score = (w, set) => (w.length === 4 ? 1 : w.length) + (new Set(w).size === 7 ? 7 : 0);
  const candidates = [];
  for (const [letters] of masks) {
    const inSet = pool.filter((w) => [...w].every((c) => letters.includes(c)));
    for (const center of letters) {
      if ("aeiou".includes(center) && Math.random() < 0) continue;
      const ans = inSet.filter((w) => w.includes(center));
      if (ans.length < 15 || ans.length > 50) continue;
      const pg = ans.filter((w) => new Set(w).size === 7);
      if (!pg.length) continue;
      const max = ans.reduce((s, w) => s + score(w), 0);
      candidates.push({ center, outer: [...letters].filter((c) => c !== center).join(""), words: ans.sort(), pangrams: pg, max });
    }
  }
  const r = rng(71121);
  const seen = new Set();
  const days = [];
  for (const c of shuffle(candidates, r)) {
    const key = [...c.outer, c.center].sort().join("");
    if (seen.has(key)) continue;
    seen.add(key);
    days.push(c);
    if (days.length >= DAYS) break;
  }
  write("comb", { launch: LAUNCH, days: days.map((d) => [d.center, d.outer, d.words.join(" ")]) });
  console.log(`Comb: ${candidates.length} letter sets, scheduled ${days.length} days, e.g. ${days[0].center.toUpperCase()}+${days[0].outer.toUpperCase()} (${days[0].words.length} words)`);
}

// ============================================================================
// THREADS: themed words snake through a 6x8 letter grid, using every letter
// ============================================================================
{
  const themes = (await import("./content/threads.mjs")).default;
  const R = 8, C = 6, N = R * C;
  const nb = [];
  for (let i = 0; i < N; i++) {
    const r = Math.floor(i / C), c = i % C, out = [];
    for (let dr = -1; dr <= 1; dr++) for (let dc = -1; dc <= 1; dc++) {
      if (!dr && !dc) continue;
      const rr = r + dr, cc = c + dc;
      if (rr >= 0 && rr < R && cc >= 0 && cc < C) out.push(rr * C + cc);
    }
    nb.push(out);
  }
  // Two diagonal steps that cross inside the same 2x2 square look ambiguous.
  const crosses = (a, b, used) => {
    const ra = Math.floor(a / C), ca = a % C, rb = Math.floor(b / C), cb = b % C;
    if (ra === rb || ca === cb) return false;
    const x = ra * C + cb, y = rb * C + ca;
    return used.has(x + "-" + y) || used.has(y + "-" + x);
  };
  function subsetSums(lengths) { let s = new Set([0]); for (const l of lengths) { const n = new Set(s); for (const v of s) n.add(v + l); s = n; } return s; }
  function components(owner) {
    const seen = new Set(), comps = [];
    for (let i = 0; i < N; i++) {
      if (owner[i] !== -1 || seen.has(i)) continue;
      let size = 0; const st = [i]; seen.add(i);
      while (st.length) { const x = st.pop(); size++; for (const y of nb[x]) if (owner[y] === -1 && !seen.has(y)) { seen.add(y); st.push(y); } }
      comps.push(size);
    }
    return comps;
  }
  function layout(list, r) {
    const owner = new Array(N).fill(-1), paths = new Array(list.length), edges = new Set();
    let budget = 60000;
    function solve(left) {
      if (!left.length) return true;
      if (--budget < 0) return false;
      // most constrained empty cell
      let start = -1, best = 9;
      for (let i = 0; i < N; i++) if (owner[i] === -1) { const f = nb[i].filter((j) => owner[j] === -1).length; if (f < best) { best = f; start = i; } }
      for (const wi of shuffle(left, r)) {
        const L = list[wi].length;
        const path = [start];
        owner[start] = wi;
        const ok = (function dfs() {
          if (path.length === L) {
            const rest = left.filter((x) => x !== wi);
            const sums = subsetSums(rest.map((x) => list[x].length));
            if (!components(owner).every((s) => sums.has(s))) return false;
            paths[wi] = [...path];
            if (solve(rest)) return true;
            return false;
          }
          const cur = path[path.length - 1];
          for (const nx of shuffle(nb[cur], r)) {
            if (owner[nx] !== -1 || crosses(cur, nx, edges)) continue;
            owner[nx] = wi; path.push(nx); edges.add(cur + "-" + nx);
            if (dfs()) return true;
            owner[nx] = -1; path.pop(); edges.delete(cur + "-" + nx);
            if (budget < 0) return false;
          }
          return false;
        })();
        if (ok) return true;
        owner[start] = -1;
        if (budget < 0) return false;
      }
      return false;
    }
    return solve(list.map((_, i) => i)) ? paths : null;
  }
  function pickWords(cands, r) {
    for (let t = 0; t < 4000; t++) {
      const pick = [], s = shuffle(cands, r);
      let sum = 0;
      for (const w of s) { if (sum + w.length <= N && pick.length < 8) { pick.push(w); sum += w.length; } if (sum === N) break; }
      if (sum === N && pick.length >= 6) return pick;
    }
    return null;
  }
  const r = rng(91121); if (process.env.SKIP_THREADS) { console.log("Threads: skipped"); } else {
  const order = shuffle(themes.map((_, i) => i), r);
  const days = [];
  for (let d = 0; days.length < DAYS; d++) {
    const [clue, list] = themes[order[d % order.length]];
    const cands = list.split(/\s+/).filter((w) => w.length >= 4 && w.length <= 10);
    let made = null;
    for (let attempt = 0; attempt < 60 && !made; attempt++) {
      const pick = pickWords(cands, r);
      if (!pick) break;
      const paths = layout(pick, r);
      if (paths) {
        const grid = new Array(N);
        pick.forEach((w, i) => paths[i].forEach((cell, k) => (grid[cell] = w[k])));
        made = { clue, grid: grid.join(""), words: pick.map((w, i) => [w, paths[i]]) };
      }
    }
    if (!made) throw new Error("Threads: could not lay out theme " + clue);
    days.push(made);
  }
  // Check: every cell used exactly once, paths are adjacent, letters match.
  for (const d of days) {
    const used = new Set();
    for (const [w, p] of d.words) {
      p.forEach((c, k) => { if (used.has(c)) throw new Error("overlap"); used.add(c); if (d.grid[c] !== w[k]) throw new Error("letter"); if (k && !nb[p[k - 1]].includes(c)) throw new Error("adjacency"); });
    }
    if (used.size !== N) throw new Error("not full");
  }
  const extra = words((w, t) => w.length >= 4 && w.length <= 9 && t <= 35);
  write("threads", { launch: LAUNCH, rows: R, cols: C, days, words: extra.join(" ") });
  console.log(`Threads: ${themes.length} themes, scheduled ${days.length} days; e.g. "${days[0].clue}": ${days[0].words.map((x) => x[0]).join(", ")}`);
  }
}

